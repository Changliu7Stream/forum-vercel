  /**
   * 将 icon-xxx 类名替换为内联 SVG
   */
  function replaceIcon(el) {
    const classes = Array.from(el.classList);
    let iconName = null;
    for (const cls of classes) {
      if (cls.startsWith('icon-')) {
        iconName = cls.replace('icon-', '');
        break;
      }
    }
    if (!iconName || !iconPaths[iconName]) return;

    const pathData = iconPaths[iconName];
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('width', '1em');
    svg.setAttribute('height', '1em');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '2');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.style.display = 'inline-block';
    svg.style.verticalAlign = 'middle';
    svg.innerHTML = pathData;

    // 替换元素本身
    el.parentNode.replaceChild(svg, el);
  }

  /**
   * 替换页面所有 icon-xxx 元素
   */
  function replaceAllIcons() {
    const iconElements = document.querySelectorAll('i[class*="icon-"]');
    // 转为数组，因为 replaceChild 会修改 DOM
    const elements = Array.from(iconElements);
    elements.forEach(replaceIcon);
  }

  // 在 DOMContentLoaded 后自动执行
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', replaceAllIcons);
  } else {
    replaceAllIcons();
  }

  // 暴露给动态渲染使用
  window.replaceIcons = replaceAllIcons;

  // 提供给 animated-icons.js 的本地 SVG 生成接口（替换 CDN 依赖）
  window.IconSVG = {
    getPath: function(name) { return iconPaths[name] || null; },
    create: function(name, size) {
      const pathData = iconPaths[name];
      if (!pathData) return null;
      const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('width', size || '1em');
      svg.setAttribute('height', size || '1em');
      svg.setAttribute('fill', 'none');
      svg.setAttribute('stroke', 'currentColor');
      svg.setAttribute('stroke-width', '2');
      svg.setAttribute('stroke-linecap', 'round');
      svg.setAttribute('stroke-linejoin', 'round');
      svg.style.display = 'inline-block';
      svg.style.verticalAlign = 'middle';
      svg.innerHTML = pathData;
      return svg;
    }
  };
